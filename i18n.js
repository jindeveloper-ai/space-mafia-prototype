export const DEFAULT_LOCALE = "ko";

export function normalizeLocale(locale) {
  return locale === "en" ? "en" : DEFAULT_LOCALE;
}

export function withJosa(word, consonantForm, vowelForm) {
  const lastCharacter = String(word).at(-1);
  const code = lastCharacter?.charCodeAt(0) ?? 0;
  const isHangulSyllable = code >= 0xac00 && code <= 0xd7a3;
  const hasFinalConsonant = isHangulSyllable && (code - 0xac00) % 28 !== 0;
  return `${word}${hasFinalConsonant ? consonantForm : vowelForm}`;
}

